// 文件名   ：seq_detect1011.v
// 内容     ：用三段式 Moore 状态机检测可重叠的 1011
// 对应笔记 ：notes/13-有限状态机.md
// 编译     ：iverilog -o fsm.vvp seq_detect1011.v seq_detect1011_mealy.v seq_detect_tb.v
//
// 读代码顺序（不要从第一行硬啃）：
//   1. 先看下面的“状态是什么”
//   2. 再看第一段：状态寄存器怎么更新
//   3. 再看第二段：case 怎么决定下一站
//   4. 最后看第三段：detected 怎么产生
//
// 一句话总结：
//   当前状态 + 当前输入 din → 查表得到 next_state
//   下一个时钟上升沿 → 把 next_state 搬进 state
//   输出只看 state，所以这是 Moore 型状态机。

module seq_detect1011 (
    input  clk,          // 时钟：只有上升沿会更新 state
    input  rst,          // 同步复位：rst=1 时，下一个上升沿回到 S0
    input  din,          // 串行输入：每个上升沿采样一位
    output detected      // 检测结果：state=S4 时为 1
);

    // -----------------------------------------------------------------------
    // 状态是什么？
    //   状态不是“现在输入是几”，而是“到目前为止匹配到哪一步”。
    //
    //   S0 : 什么都没匹配到                    （已匹配：空）
    //   S1 : 当前有用的后缀是 1                （已匹配："1"）
    //   S2 : 当前有用的后缀是 10               （已匹配："10"）
    //   S3 : 当前有用的后缀是 101              （已匹配："101"）
    //   S4 : 刚刚收到完整的 1011，所以输出 1    （已匹配："1011"）
    //
    //   3 位二进制能表示 8 种编码，这里只用了 5 种。
    // -----------------------------------------------------------------------
    localparam [2:0] S0 = 3'b000,
                     S1 = 3'b001,
                     S2 = 3'b010,
                     S3 = 3'b011,
                     S4 = 3'b100;

    // state      ：真正的寄存器。只在时钟上升沿被 <= 更新。
    // next_state ：组合逻辑算出的“下一站”。它本身不记忆，只是连线上的值。
    reg [2:0] state;
    reg [2:0] next_state;

    // -----------------------------------------------------------------------
    // 第一段：状态寄存器（时序逻辑）
    //
    //   这一段不计算转移，只负责“记住”。
    //   上升沿到来时：
    //     rst=1  → 回到 S0
    //     rst=0  → 把第二段算好的 next_state 搬进 state
    // -----------------------------------------------------------------------
    always @(posedge clk) begin
        if (rst)
            state <= S0;         // 复位优先，回到起点
        else
            state <= next_state; // 非阻塞赋值：沿上统一更新
    end

    // -----------------------------------------------------------------------
    // 第二段：次态逻辑（组合逻辑）
    //
    //   输入：当前 state + din
    //   输出：next_state
    //   写法：case 选择当前状态，再用 if/else 看 din 是 0 还是 1。
    //
    //   开头的 next_state = state 是“默认保持”，保证任何路径都有赋值，
    //   这样不会因为漏写分支而综合出锁存器。
    // -----------------------------------------------------------------------
    always @(*) begin
        next_state = state;      // 默认值：没写到的情况先保持原状态

        case (state)

            // S0：还没开始匹配
            //   din=0 → 还是空，继续等
            //   din=1 → 成功匹配第一位，去 S1
            S0: begin
                if (din) next_state = S1;
                else     next_state = S0;
            end

            // S1：已经匹配 "1"
            //   din=0 → 拼成 "10"，去 S2
            //   din=1 → 拼成 "11"，末尾的 1 仍可作为新开头，留在 S1
            S1: begin
                if (din) next_state = S1;
                else     next_state = S2;
            end

            // S2：已经匹配 "10"
            //   din=1 → 拼成 "101"，去 S3
            //   din=0 → 拼成 "100"，没有可用后缀，回 S0
            S2: begin
                if (din) next_state = S3;
                else     next_state = S0;
            end

            // S3：已经匹配 "101"
            //   din=1 → 拼成 "1011"，命中，去 S4
            //   din=0 → 拼成 "1010"，末尾 "10" 还有用，退回 S2
            //           注意：这里不是回 S0
            S3: begin
                if (din) next_state = S4;
                else     next_state = S2;
            end

            // S4：刚刚命中 "1011"，但输入流还在继续
            //   din=1 → 拼成 "10111"，末尾的 1 可当新序列开头，去 S1
            //   din=0 → 拼成 "10110"，末尾的 10 可当新序列开头，去 S2
            //   这两条出边让检测器支持重叠匹配。
            S4: begin
                if (din) next_state = S1;
                else     next_state = S2;
            end

            // 如果仿真/硬件跑到未定义编码，统一回到 S0，避免卡死。
            default: next_state = S0;
        endcase
    end

    // -----------------------------------------------------------------------
    // 第三段：输出逻辑（Moore 型）
    //
    //   Moore：输出只由当前 state 决定。
    //   因此 state 进入 S4 后，detected 变成 1；
    //   state 离开 S4 后，detected 自动变回 0。
    // -----------------------------------------------------------------------
    assign detected = (state == S4);

endmodule