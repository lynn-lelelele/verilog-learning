// ============================================================
// 文件名   ：assign.v
// 内容     ：用 assign 连续赋值实现 7 种基本逻辑门
// 说明     ：每个 module 是一个独立的电路单元，可被测试台或其他模块实例化
// 对应笔记 ：notes/01-门电路.md、notes/02-assign语法.md
// 编译检查 ：iverilog -o gates.vvp assign.v
// ============================================================

// ------------------------------------------------------------
// 模块名 ：and_gate
// 功能   ：2 输入与门
// 逻辑式 ：y = a & b
// 真值   ：仅当 a=1 且 b=1 时 y=1，其余为 0
// 端口   ：a, b 输入（1 位）；y 输出（1 位）
// ------------------------------------------------------------
module and_gate (
    input  a,               // 输入 a
    input  b,               // 输入 b
    output y                // 输出 y
);

    // 连续赋值：y 始终等于 a & b
    // 语义是“持续维持等式”，不是“执行一次”；a/b 变化时重新求值，结果可能不变
    assign y = a & b;

endmodule


// ------------------------------------------------------------
// 模块名 ：or_gate
// 功能   ：2 输入或门
// 逻辑式 ：y = a | b
// 真值   ：任一输入为 1 则 y=1，仅当 a=0 且 b=0 时 y=0
// ------------------------------------------------------------
module or_gate (
    input  a,
    input  b,
    output y
);

    assign y = a | b;

endmodule


// ------------------------------------------------------------
// 模块名 ：not_gate
// 功能   ：非门（反相器）
// 逻辑式 ：y = ~a
// 真值   ：输入取反
// 说明   ：只有一个输入端口
// ------------------------------------------------------------
module not_gate (
    input  a,
    output y
);

    assign y = ~a;

endmodule


// ------------------------------------------------------------
// 模块名 ：nand_gate
// 功能   ：2 输入与非门（与门后接反相）
// 逻辑式 ：y = ~(a & b)
// 真值   ：仅当 a=1 且 b=1 时 y=0，其余为 1
// 注意   ：括号不能省，~(a & b) 与 ~a & b 不等价
// ------------------------------------------------------------
module nand_gate (
    input  a,
    input  b,
    output y
);

    assign y = ~(a & b);

endmodule


// ------------------------------------------------------------
// 模块名 ：nor_gate
// 功能   ：2 输入或非门（或门后接反相）
// 逻辑式 ：y = ~(a | b)
// 真值   ：仅当 a=0 且 b=0 时 y=1，其余为 0
// 注意   ：同样依赖括号保证运算顺序
// ------------------------------------------------------------
module nor_gate (
    input  a,
    input  b,
    output y
);

    assign y = ~(a | b);

endmodule


// ------------------------------------------------------------
// 模块名 ：xor_gate
// 功能   ：2 输入异或门
// 逻辑式 ：y = a ^ b
// 真值   ：两输入不同（0/1 或 1/0）时 y=1，相同时 y=0
// ------------------------------------------------------------
module xor_gate (
    input  a,
    input  b,
    output y
);

    assign y = a ^ b;

endmodule


// ------------------------------------------------------------
// 模块名 ：xnor_gate
// 功能   ：2 输入同或门（异或后接反相）
// 逻辑式 ：y = ~(a ^ b)
// 真值   ：两输入相同（同 0 或同 1）时 y=1，不同时 y=0
// ------------------------------------------------------------
module xnor_gate (
    input  a,
    input  b,
    output y
);

    assign y = ~(a ^ b);

endmodule
