// ============================================================
// 文件名   ：or_gate_tb.v
// 作用     ：或门 or_gate 的测试台，仅用于仿真，不参与综合
// 说明     ：测试台相当于“电源 + 开关 + 万用表”，逐组施加输入并记录输出
// 预期输出 ：a=0 b=0 y=0
//            a=0 b=1 y=1
//            a=1 b=0 y=1
//            a=1 b=1 y=1
// 运行     ：iverilog -o tb.vvp assign.v or_gate_tb.v
//            vvp tb.vvp
// ============================================================
module or_gate_tb;                 // 测试台没有对外引脚，括号里留空

    // ---------------- 第一段：声明信号 ----------------
    reg  a;                        // a 由测试台主动赋值，所以是 reg
    reg  b;                        // b 同上
    wire y;                        // y 由被测电路驱动，测试台只观察，所以是 wire

    // ---------------- 第二段：实例化被测电路 ----------------
    or_gate dut (                  // dut 是这块电路的代号（device under test）
        .a(a),                     // 电路 a 脚  ← 测试台 a 线
        .b(b),                     // 电路 b 脚  ← 测试台 b 线
        .y(y)                      // 电路 y 脚  → 测试台 y 线
    );

    // ---------------- 第三段：激励（按时间顺序干活） ----------------
    initial begin                  // 0 时刻开始执行，且只执行一次

        // 第 1 种输入：a=0, b=0
        a = 0; b = 0;              // 阻塞赋值：这两句立刻生效
        #10;                       // 等 10 个时间单位，让电路稳定
        $display("a=%b b=%b y=%b", a, b, y);   // %b = 用二进制打印

        // 第 2 种输入：a=0, b=1
        a = 0; b = 1;
        #10;
        $display("a=%b b=%b y=%b", a, b, y);

        // 第 3 种输入：a=1, b=0
        a = 1; b = 0;
        #10;
        $display("a=%b b=%b y=%b", a, b, y);

        // 第 4 种输入：a=1, b=1
        a = 1; b = 1;
        #10;
        $display("a=%b b=%b y=%b", a, b, y);

        $finish;                   // 结束仿真，不写会一直挂在那里
    end

endmodule
