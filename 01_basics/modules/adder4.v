// 文件名   ：adder4.v
// 内容     ：4 位行波进位加法器（Ripple Carry Adder）
// 对应笔记 ：notes/10-全加器.md（n 位扩展一节）
// 依赖     ：full_adder.v、half_adder.v
// 编译     ：iverilog -o adder4.vvp half_adder.v full_adder.v adder4.v adder4_tb.v
//
// 结构：
//   四个 1 位全加器并排，低位的 cout 接高位的 cin，进位像波浪一样逐级往上传：
//
//        a[3] b[3]        a[2] b[2]        a[1] b[1]        a[0] b[0]
//          │   │            │   │            │   │            │   │
//        ┌─▼───▼──┐      ┌─▼───▼──┐      ┌─▼───▼──┐      ┌─▼───▼──┐
//        │   u3   │      │   u2   │      │   u1   │      │   u0   │
//  cout ◄│        │◄─c3─│        │◄─c2─│        │◄─c1─│        │◄── cin
//        └────┬───┘      └────┬───┘      └────┬───┘      └────┬───┘
//           sum[3]          sum[2]          sum[1]          sum[0]

module adder4 (
    input  [3:0] a,      // 被加数
    input  [3:0] b,      // 加数
    input        cin,    // 最低位的进位输入（纯加法可接 1'b0）
    output [3:0] sum,    // 4 位本位和
    output       cout    // 最高位送出的进位，也就是“溢出位”
);

    // ---------------------------------------------------------------
    // 中间进位：不在端口列表里，是模块内部自己拉的三根线
    // 每根都连接“低一位的 cout”和“高一位的 cin”
    // 忘记声明会编译不报错，但仿真结果全是 x
    // ---------------------------------------------------------------
    wire c1, c2, c3;

    // ---------------------------------------------------------------
    // 四个全加器实例：模块名 full_adder，实例名 u0~u3
    // 注意每个端口接的都是“一位”：a[0]、b[0]、sum[0]
    // ---------------------------------------------------------------

    // 第 0 位（最低位）：cin 来自外部，进位输出给 c1
    full_adder u0 (
        .a(a[0]), .b(b[0]), .cin(cin),
        .sum(sum[0]), .cout(c1)
    );

    // 第 1 位：cin 接 c1，进位输出给 c2
    full_adder u1 (
        .a(a[1]), .b(b[1]), .cin(c1),
        .sum(sum[1]), .cout(c2)
    );

    // 第 2 位：cin 接 c2，进位输出给 c3
    full_adder u2 (
        .a(a[2]), .b(b[2]), .cin(c2),
        .sum(sum[2]), .cout(c3)
    );

    // 第 3 位（最高位）：cin 接 c3，进位输出直接给端口 cout
    full_adder u3 (
        .a(a[3]), .b(b[3]), .cin(c3),
        .sum(sum[3]), .cout(cout)
    );

endmodule
