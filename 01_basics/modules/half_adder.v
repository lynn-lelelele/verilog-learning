// ------------------------------------------------------------
// 模块名 ：half_adder
// 功能   ：计算 a + b 的“本位和”和“进位”
//
// 两个输出的含义（对应十进制里 1 + 1 = 10 的写法）：
//   sum  —— 本位和：这一位最后写下的数字，即 a + b 的个位
//   cout —— 进位：向高一位送出去的 1，即 a + b 的十位
//
// 十进制类比：5 + 7 = 12，个位写 2、向十位进 1。
// 二进制同理：1 + 1 = 10，本位写 0、向高位进 1。
//
// 真值表：
//   a b | sum cout | 说明
//   0 0 |  0   0   | 0+0 = 0，不进位
//   0 1 |  1   0   | 0+1 = 1，不进位
//   1 0 |  1   0   | 1+0 = 1，不进位
//   1 1 |  0   1   | 1+1 = 10，本位 0、进位 1
// ------------------------------------------------------------
module half_adder (
    input  a,       // 加数
    input  b,       // 被加数
    output sum,     // 本位和：a 与 b 不同时为 1，相同时为 0
    output cout     // 进位：只有 a、b 同时为 1 才产生进位
);

    // 本位和用异或：两个输入不同则输出 1，相同则输出 0
    // 1+1 时两个都是 1，异或得 0，正好是“写 0 进 1”里的那个 0
    assign sum = a ^ b;

    // 进位用与：只有两个输入都是 1，才够“满 2 进 1”
    assign cout = a & b;

endmodule

