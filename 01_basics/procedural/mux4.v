// 文件名   ：mux4.v
// 内容     ：4 选 1 多路选择器，两种写法（case / if-else），功能完全相同
// 对应笔记 ：notes/11-always与组合逻辑.md
// 编译     ：iverilog -o mux4.vvp mux4.v mux4_tb.v
//
// 概念速查：
//   sel = select（选择信号），2 位，取值 00/01/10/11，像一个频道号，
//         决定把 d[0]~d[3] 中的哪一路送到 y。
//   always @(*) = 组合逻辑：输入变就重算，不存值，没有时钟。
//   y 声明为 reg = “可以被 always 赋值”，不代表生成寄存器。

// ---------------------------------------------------------------------------
// 写法一：case
//   sel 的 4 种取值各选一路。4 条分支全部写出，覆盖了 2 位信号的所有可能，
//   因此任何时刻 y 都有确定的值，不会推断出锁存器。
// ---------------------------------------------------------------------------
module mux4_case (
    input  [3:0] d,      // 4 路输入：d[3] d[2] d[1] d[0]
    input  [1:0] sel,    // 选择信号：sel[1] 是高位，sel[0] 是低位
    output reg   y       // 被 always 赋值，必须是 reg
);

    always @(*) begin             // 敏感列表用 *，d 或 sel 一变就重新执行
        case (sel)                // 拿 sel 的值逐条比较，命中即跳出
            2'b00: y = d[0];      // sel = 0 → 选第 0 路
            2'b01: y = d[1];      // sel = 1 → 选第 1 路
            2'b10: y = d[2];      // sel = 2 → 选第 2 路
            2'b11: y = d[3];      // sel = 3 → 选第 3 路
        endcase                   // 4 种取值全覆盖，没有遗漏分支
    end

endmodule


// ---------------------------------------------------------------------------
// 写法二：if-else（嵌套两层）
//   判断顺序：先看 sel 高位，再看低位，像一棵二叉树的两次分叉：
//       sel[1]=0 ─ sel[0]=0 → d[0]
//                └ sel[0]=1 → d[1]
//       sel[1]=1 ─ sel[0]=0 → d[2]
//                └ sel[0]=1 → d[3]
// ---------------------------------------------------------------------------
module mux4_if (
    input  [3:0] d,
    input  [1:0] sel,
    output reg   y
);

    always @(*) begin
        y = 1'b0;                  // 默认值：保证任何路径都先有一个值

        if (sel[1]) begin          // 第 1 层：判断高位
            if (sel[0]) y = d[3];  // 11 → 第 3 路
            else        y = d[2];  // 10 → 第 2 路
        end
        else begin                 // 高位为 0 的情况
            if (sel[0]) y = d[1];  // 01 → 第 1 路
            else        y = d[0];  // 00 → 第 0 路
        end
    end

endmodule
