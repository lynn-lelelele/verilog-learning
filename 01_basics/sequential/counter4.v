// 文件名   ：counter4.v
// 内容     ：4 位同步复位计数器（时序逻辑的第一个完整例子）
// 对应笔记 ：notes/12-时钟与触发器.md
// 编译     ：iverilog -o counter4.vvp counter4.v counter4_tb.v
//
// 要点：
//   1. always @(posedge clk)：只在时钟上升沿执行一次
//   2. q 在过程块里被赋值 → 必须声明为 reg
//   3. 时序逻辑用非阻塞赋值 <=，不用 =

module counter4 (
    input           clk,    // 时钟，上升沿有效
    input           rst,    // 同步复位：rst=1 时，下一个上升沿清零
    output reg [3:0] q      // 计数值 0~15，每个时钟沿加 1
);

    always @(posedge clk) begin
        if (rst) q <= 4'd0;      // 复位优先：清零
        else     q <= q + 1'b1;  // 否则加 1；加到 15 再加就溢出回 0
    end

endmodule


// ---------------------------------------------------------------------------
// 补充说明：
//   1. 这里是“同步复位”——复位要等时钟沿才生效。
//      若写成 always @(posedge clk or posedge rst)，
//      就变成“异步复位”，rst 一拉高立刻清零，不用等时钟。
//   2. 4 位最多数到 15，q + 1 溢出的部分被丢弃，所以自然形成 0~15 循环。
//   3. 这个计数器同时也是分频器：16 个时钟周期，q[3] 才翻转一次。
// ---------------------------------------------------------------------------
