// 文件名   ：counter4.v
// 内容     ：4 位同步复位计数器（时序逻辑的第一个完整例子）
// 对应笔记 ：notes/12-时钟与触发器.md 第 5、6 节
// 编译     ：iverilog -o counter4.vvp counter4.v counter4_tb.v
//
// 要点：
//   1. always @(posedge clk)：只在时钟上升沿执行一次
//   2. q 在过程块里被赋值 → 必须声明为 reg
//   3. 时序逻辑用非阻塞赋值 <=，不用 =

module counter4 (
    input           clk,    // 时钟：只有它的上升沿（0→1）能触发下面的块
    input           rst,    // 同步复位：rst=1 时，要等到下一个上升沿才清零
    output reg [3:0] q      // 计数值 0~15；被 always 赋值，所以是 reg
);

    // 逐行拆解：
    //
    //   always @(posedge clk) begin
    //     │       │           │    └ 块体开始，与最后的 end 配对
    //     │       │           └ posedge clk：clk 从 0 变 1 的瞬间唤醒本块
    //     │       └ @(...)：事件列表，写“什么情况下执行”
    //     └ always：过程块，可以被反复触发
    //
    //   if (rst) q <= 4'd0;
    //     │      │  └ 1'b0 的 4 位版：把 q 写成 0
    //     │      └ <= 非阻塞赋值：本拍所有语句执行完后统一写入
    //     └ 时钟沿到来的那一刻检查 rst，为 1 就清零
    //
    //   else     q <= q + 1'b1;
    //     └ rst 为 0 才执行；右边是“旧的 q 加 1”，所以每拍只加一次
    //
    // 注意：rst 不在敏感列表里，它自己变高不会触发本块，
    //       必须等到下一个时钟沿才被“顺便”读到——这就是“同步”。
    always @(posedge clk) begin

        // if / else 的先后顺序决定优先级：
        //   只要 rst 为 1，就执行上一行（清零），下一行的计数逻辑被完全跳过。
        // 写成 else 而不是两个独立的 if，保证“复位”和“计数”互斥，
        // 同一个时钟沿绝不会既清零又加一。
        if (rst) q <= 4'd0;      // 复位优先：清零

        // 时序逻辑用 <=（非阻塞）：
        //   右边的 q 取的是“本拍更新前”的旧值，
        //   所以这一句等价于“下一拍 = 这一拍 + 1”，不会自己叠加两次。
        else     q <= q + 1'b1;  // 正常计数；15 + 1 溢出，自动回 0

    end                          // 块体结束

endmodule


// ---------------------------------------------------------------------------
// 补充说明：
//
//   1. 同步 vs 异步复位
//      同步：always @(posedge clk)                → 等时钟沿才清零
//      异步：always @(posedge clk or posedge rst) → rst 一变高立刻清零
//      想实际看区别，跑 reset_compare_tb.v：
//      iverilog -o reset.vvp counter4.v counter4_async.v reset_compare_tb.v
//
//   2. 为什么开头会看到 x
//      reg 上电初值是 x（未知）。如果台子里一上来 rst=0，
//      那么 q <= q + 1 就是 x + 1 = x，永远是 x。
//      所以测试台必须“先复位、再放开”。
//
//   3. 溢出行为
//      4 位最多表示 15，q + 1 的第 5 位被丢弃，于是 15 → 0，
//      形成 0~15 的自然循环，不需要写 if (q == 15) q <= 0。
//
//   4. 分频作用
//      q[0] 每 2 个时钟周期翻转一次，q[1] 每 4 个，
//      q[3] 每 16 个——这就是分频器，后面驱动数码管、蜂鸣器都要用。
// ---------------------------------------------------------------------------
