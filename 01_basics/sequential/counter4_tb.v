// 文件名   ：counter4_tb.v
// 内容     ：4 位计数器的测试台，重点是“如何产生时钟”
// 被测模块 ：counter4
// 编译     ：iverilog -o counter4.vvp counter4.v counter4_tb.v
// 运行     ：vvp counter4.vvp
//
// 预期行为：
//   t=0~20  rst=1，每个上升沿 q 都被清 0
//   t=22    rst 拉低（放在时钟沿之后，避免和沿同刻产生竞争）
//   t=30 起 每个上升沿 q 加 1：1, 2, 3 ... 15, 0, 1 ...
//   t=200   $finish 结束

module counter4_tb;

    reg        clk;     // 测试台自己制造的时钟
    reg        rst;     // 复位开关
    wire [3:0] q;       // 计数器输出，只观察

    counter4 dut ( .clk(clk), .rst(rst), .q(q) );

    // ---------------------------------------------------------------
    // 时钟发生器：这是时序测试台和组合测试台最大的区别
    //   #5 翻转一次 → 高低各 5 个时间单位 → 周期 10
    //   forever 是死循环，靠下面的 $finish 结束
    // ---------------------------------------------------------------
    initial begin
        clk = 1'b0;
        forever #5 clk = ~clk;
    end

    // ---------------------------------------------------------------
    // 复位与停机：只负责“什么时候放开复位、什么时候结束”
    // ---------------------------------------------------------------
    initial begin
        rst = 1'b1;      // 上电先复位
        #22;             // 保持 22 个时间单位（跨过 t=20 的上升沿）
        rst = 1'b0;      // 放开复位
        #178;            // 再跑 178，总计到 t=200
        $finish;
    end

    // ---------------------------------------------------------------
    // 观察器：每个上升沿等 1 个单位再打印
    //   为什么要 #1：打印块和计数器块都在上升沿触发，
    //   同一时刻谁先执行不确定；等 1 个单位，q 已经更新完，读到的一定是新值
    //   %0t 打印当前仿真时间，%2d 十进制补位，%b 二进制
    // ---------------------------------------------------------------
    always @(posedge clk) begin
        #1;
        $display("t=%0t ns  rst=%b  q=%2d (%b)", $time, rst, q, q);
    end

endmodule
