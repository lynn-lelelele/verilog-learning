// ============================================================
// 文件名   ：nibble_swap.v
// 功能     ：将 8 位数据的高 4 位与低 4 位（nibble）互换
// 输入     ：a[7:0]
// 输出     ：y[7:0]
// 映射关系 ：y[7:4] = a[3:0]，y[3:0] = a[7:4]
// 对应笔记 ：notes/05-向量.md（第 4 节有连线图）
// ============================================================
module nibble_swap (
    input  [7:0] a,         // 待换位的 8 位数据，a[7] 为最高位
    output [7:0] y          // 换位结果
);

    // 花括号 { } 为位拼接：写在前面的元素占据结果的高位
    // 第一个元素 a[3:0]（低 4 位）→ 落到 y[7:4]
    // 第二个元素 a[7:4]（高 4 位）→ 落到 y[3:0]
    assign y = {a[3:0], a[7:4]};

endmodule
