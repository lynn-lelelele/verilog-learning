// ============================================================
// 文件名   ：nibble_swap_tb.v
// 作用     ：nibble_swap 的测试台，仅用于仿真，不参与综合
// 用例     ：8'b1010_0011 —— 高低半字节不同，便于观察对调是否发生
//            8'hFF        —— 全 1，检查边界情况
// 预期输出 ：a=10100011 y=00111010
//            a=11111111 y=11111111
// 运行     ：iverilog -o swap.vvp nibble_swap.v nibble_swap_tb.v
//            vvp swap.vvp
// ============================================================
module nibble_swap_tb;

    // ---------------- 信号声明 ----------------
    reg  [7:0] a;           // 激励信号：测试台主动赋值 → reg，并带位宽
    wire [7:0] y;           // 观测信号：由被测电路驱动 → wire

    // ---------------- 实例化被测电路 ----------------
    nibble_swap dut (
        .a(a),              // 端口 a ← 测试台 a
        .y(y)               // 端口 y → 测试台 y
    );

    // ---------------- 激励 ----------------
    initial begin

        // 用例 1：高低半字节不同，验证是否对调
        a = 8'b1010_0011;   // 位宽 8、二进制，下划线仅为易读，可省略
        #10;                // 等待组合逻辑稳定
        $display("a=%b y=%b", a, y);

        // 用例 2：全 1，验证边界情况下输出不被破坏
        a = 8'hFF;
        #10;
        $display("a=%b y=%b", a, y);

        $finish;            // 结束仿真，否则会一直挂起
    end

endmodule
