// ------------------------------------------------------------
// 模块名 ：replicate
// 功能   ：把 1 位信号复制成 4 位
// 逻辑式 ：y = {4{a}}
// 结果   ：a=1 → 1111；a=0 → 0000
// ------------------------------------------------------------
module replicate (
    input  a,               // 1 位输入
    output [3:0] y          // 4 位输出，四位取值相同
);

    // {4{a}} 中 4 是常数次数，a 是被复制的内容
    assign y = {4{a}};

endmodule


// ------------------------------------------------------------
// 模块名 ：shift_left2
// 功能   ：8 位数据左移 2 位
// 逻辑式 ：y = a << 2
// 说明   ：高位被挤掉，低位补 0，位宽保持 8 位不变
// ------------------------------------------------------------
module shift_left2 (
    input  [7:0] a,
    output [7:0] y
);

    assign y = a << 2;

endmodule


// ------------------------------------------------------------
// 模块名 ：shift_right3
// 功能   ：8 位数据逻辑右移 3 位
// 逻辑式 ：y = a >> 3
// 说明   ：低位被挤掉，高位补 0
// ------------------------------------------------------------
module shift_right3 (
    input  [7:0] a,
    output [7:0] y
);

    assign y = a >> 3;

endmodule


// ------------------------------------------------------------
// 模块名 ：zero_extend
// 功能   ：4 位无符号数扩展成 8 位，高位补 0
// 逻辑式 ：y = {4'b0000, a}
// 说明   ：直接 assign y = a 也会隐式补 0，这里显式写出，避免依赖默认规则
// ------------------------------------------------------------
module zero_extend (
    input  [3:0] a,
    output [7:0] y
);

    // --------------------------------------------------------
    // 这一行拆开读：assign y = { 4'b0000 , a };
    //
    // {}       拼接运算符：把花括号里用逗号隔开的几段，从左到右并排拼成一根更宽的线
    // 4'b0000  4 位常量，值全为 0。4 是位宽，b 是二进制，0000 是数值
    // a        端口声明的 4 位输入，本身就是 4 根线
    //
    // 拼接后总宽度 = 4 + 4 = 8 位，正好等于 y 的位宽
    // 花括号中左边的放高位，右边的放低位，所以结果是：
    //     y[7:4] = 0000      ← 来自常量
    //     y[3:0] = a[3:0]    ← 来自输入，原样保留
    //
    // 举例：a = 4'b1111 时，y = 0000_1111
    //       a = 4'b1010 时，y = 0000_1010
    //
    // 注意：直接写 assign y = a; 也会隐式补 0，得到同样结果
    //       这里显式拼接，是为了让“高位补 4 个 0”这件事写在代码里，不依赖默认规则
    // --------------------------------------------------------
    assign y = {4'b0000, a};

endmodule
