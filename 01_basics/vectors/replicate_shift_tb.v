// ============================================================
// 文件名   ：replicate_shift_tb.v
// 内容     ：验证复制、左移、右移、补零四个模块
// 对应笔记 ：notes/07-复制与移位.md
// 运行     ：iverilog -o demo.vvp replicate_shift.v replicate_shift_tb.v
//            vvp demo.vvp
// 预期输出 ：
//   复制  a=1 y=1111
//   复制  a=0 y=0000
//   左移2 a=10010110 y=01011000
//   右移3 a=10010110 y=00010010
//   补零  a=1111 y=00001111
//
// 结构说明 ：
//   一个 testbench 可以同时放多个被测电路，它们像并排插在同一块面包板上，
//   共用一条仿真时间轴。没有给输入的那几块电路输出保持不变，
//   拨哪根输入线，就只有接在这根线上的电路会响应。
// ============================================================

module replicate_shift_tb;

    // --------------------------------------------------------
    // 第一组：复制模块
    // a1 是测试台自己拨的开关，所以要 reg；
    // y_rep 由被测电路驱动，测试台只读，所以要 wire。
    // --------------------------------------------------------
    reg        a1;
    wire [3:0] y_rep;

    // --------------------------------------------------------
    // 第二组：两个移位模块共用一根输入线
    // a2 只有一根，它同时接到 shift_left2 和 shift_right3，
    // 拨一次，两个电路同时看到同一个 8 位输入，
    // 但输出分别走 y_shl 和 y_shr 两根线，可以分别观察。
    // --------------------------------------------------------
    reg  [7:0] a2;
    wire [7:0] y_shl;
    wire [7:0] y_shr;

    // --------------------------------------------------------
    // 第三组：补零模块
    // --------------------------------------------------------
    reg  [3:0] a3;
    wire [7:0] y_ext;

    // --------------------------------------------------------
    // 实例化：把四块电路“插”到测试台上
    // 这一步只是接好线，还没有通电，所有信号此刻都是未知值 x。
    // .a(a1) 读法：点号左边是被测电路的引脚名，括号里是测试台的线名。
    // --------------------------------------------------------
    replicate    dut_rep ( .a(a1), .y(y_rep) );   // 复制：1 位 → 4 位
    shift_left2  dut_shl ( .a(a2), .y(y_shl) );   // 左移 2 位
    shift_right3 dut_shr ( .a(a2), .y(y_shr) );   // 右移 3 位
    zero_extend  dut_ext ( .a(a3), .y(y_ext) );   // 4 位 → 8 位补零

    // --------------------------------------------------------
    // 激励：从 0 时刻开始，按顺序执行一次
    // 每一组都是“拨开关 → 等 10 个时间单位 → 打印”，
    // 等待是为了让电路有稳定的时间，打印时读到的才是确定值。
    // --------------------------------------------------------
    initial begin

        // 用例 1：复制模块，测 1 和 0 两种输入，覆盖 1111 和 0000
        a1 = 1'b1; #10;
        $display("复制  a=%b y=%b", a1, y_rep);
        a1 = 1'b0; #10;
        $display("复制  a=%b y=%b", a1, y_rep);

        // 用例 2：两个移位模块
        // 选一个高低位都有 1 的数据，便于观察哪些位被挤掉、哪些位补 0
        a2 = 8'b1001_0110; #10;
        // 下面两行之间没有 #10，仿真时间没有前进，
        // 相当于同一时刻读两块电路的输出，这就是“同时测量”的写法
        $display("左移2 a=%b y=%b", a2, y_shl);
        $display("右移3 a=%b y=%b", a2, y_shr);

        // 用例 3：补零模块，4 位全 1 扩展后高 4 位必须是 0
        a3 = 4'b1111; #10;
        $display("补零  a=%b y=%b", a3, y_ext);

        $finish;    // 结束仿真，不写这行仿真器会一直挂着

    end

endmodule

// ============================================================
// 时间轴（对照实际输出看）
//   时间 0 ：a1 拨到 1，开始计时
//   时间 10：打印“复制 a=1 y=1111”，同时把 a1 拨到 0
//   时间 20：打印“复制 a=0 y=0000”，同时把 a2 拨到 1001_0110
//   时间 30：连续打印左移、右移两行，同时把 a3 拨到 1111
//   时间 40：打印“补零 a=1111 y=00001111”，然后 $finish
// ============================================================
